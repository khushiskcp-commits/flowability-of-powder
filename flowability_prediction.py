def find_category(value, column_number):

    for _, row in reference.iterrows():

        range_text = row.iloc[column_number]

        if value_in_range(value, range_text):
            return str(row.iloc[0]).strip().title()

    return "Outside Reference Range"

print("Category finder created successfully!")

find_category(27, 1)

find_category(1.19, 2)

find_category(15, 3)

def analyze_flow(angle, carr, hausner):

    angle_result = find_category(angle, 1)
    carr_result = find_category(carr, 2)
    hausner_result = find_category(hausner, 3)

    results = [
        angle_result,
        carr_result,
        hausner_result
    ]

    valid_results = [
        result for result in results
        if result != "Outside Reference Range"
    ]

    if len(valid_results) == 0:
        final_result = "No valid classification"

    else:
        counts = pd.Series(valid_results).value_counts()

        if counts.iloc[0] >= 2:
            final_result = counts.index[0]
        else:
            final_result = "Review Required"

    return (
        angle_result,
        carr_result,
        hausner_result,
        final_result
    )


