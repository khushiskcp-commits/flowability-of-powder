import re

def value_in_range(value, range_text):

    text = str(range_text).strip().lower()
    text = text.replace(" ", "")

    # Range such as 31-35
    if "-" in text:
        parts = text.split("-")

        if len(parts) == 2:
            try:
                minimum = float(parts[0])
                maximum = float(parts[1])

                return minimum <= value <= maximum
            except:
                pass
# Range such as 11to15
    if "to" in text:
        parts = text.split("to")

        if len(parts) == 2:
            try:
                minimum = float(parts[0])
                maximum = float(parts[1])

                return minimum <= value <= maximum
            except:
                pass

    # Less than or equal to
    if "≤" in text:
        number = text.replace("≤", "")
        try:
            maximum = float(number)
            return value <= maximum
        except:
            pass

    # Greater than or equal to
    if "≥" in text:
        number = text.replace("≥", "")

        try:
            minimum = float(number)
            return value >= minimum
        except:
            pass
            # Greater than
    if text.startswith(">"):
        try:
            minimum = float(text.replace(">", ""))
            return value > minimum
        except:
            pass

    return False

